#!/usr/bin/env node
// Generates docs/audio-checklist.md: every audio file the content references,
// what Telugu to say in it, and whether it already exists in public/audio.
// Re-run after adding lessons or recordings:  node scripts/audio-checklist.mjs

import { readdirSync, readFileSync, existsSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const lessonsDir = join(root, 'src', 'content', 'lessons');
const storiesDir = join(root, 'src', 'content', 'stories');
const publicDir = join(root, 'public');
const outPath = join(root, '..', 'docs', 'audio-checklist.md');

/** path → { telugu, translit, english, sources:Set, slow:boolean } */
const files = new Map();

function add(path, text, source, isSlow = false) {
  if (!path) return;
  const key = path;
  const entry = files.get(key) ?? { telugu: '', translit: '', english: '', sources: new Set(), slow: isSlow };
  if (text?.telugu && !entry.telugu) entry.telugu = text.telugu;
  if (text?.transliteration && !entry.translit) entry.translit = text.transliteration;
  if (text?.english && !entry.english) entry.english = text.english;
  entry.sources.add(source);
  files.set(key, entry);
}

function walkAudio(ref, text, source) {
  if (!ref) return;
  add(ref.normal, text, source, false);
  add(ref.slow, text ? { ...text, english: (text.english ?? '') + ' (slow, clearly separated)' } : text, source, true);
}

function walkExercise(ex, source) {
  const spoken = ex.spoken ?? ex.source ?? ex.model ?? null;
  walkAudio(ex.audio, spoken, source);
  if (ex.spoken?.audio) walkAudio(ex.spoken.audio, ex.spoken, source);
  if (ex.source?.audio) walkAudio(ex.source.audio, ex.source, source);
  if (ex.model?.audio) walkAudio(ex.model.audio, ex.model, source);
  if (ex.target?.audio) walkAudio(ex.target.audio, ex.target, source);
  for (const t of ex.turns ?? []) if (t.line?.audio) walkAudio(t.line.audio, t.line, source);
  for (const c of ex.choices ?? []) if (c.audio) walkAudio(c.audio, c, source);
}

for (const f of readdirSync(lessonsDir).filter((x) => x.endsWith('.json'))) {
  const lesson = JSON.parse(readFileSync(join(lessonsDir, f), 'utf8'));
  for (const ex of lesson.exercises ?? []) walkExercise(ex, lesson.id);
}
if (existsSync(storiesDir)) {
  for (const f of readdirSync(storiesDir).filter((x) => x.endsWith('.json'))) {
    const story = JSON.parse(readFileSync(join(storiesDir, f), 'utf8'));
    story.lines?.forEach((l, i) => {
      if (l.line?.audio) walkAudio(l.line.audio, l.line, `${story.id} line ${i + 1}`);
    });
    for (const cp of story.checkpoints ?? []) walkExercise(cp.exercise, story.id);
  }
}

// group by directory
const byDir = new Map();
for (const [path, entry] of files) {
  const dir = path.slice(0, path.lastIndexOf('/'));
  if (!byDir.has(dir)) byDir.set(dir, []);
  byDir.get(dir).push({ path, ...entry });
}

let done = 0, missing = 0;
const lines = [];
lines.push('# Audio recording checklist');
lines.push('');
lines.push('Generated by `node learn-app/scripts/audio-checklist.mjs` — re-run any time.');
lines.push('');
lines.push('**How to record:** one MP3 per row, spoken once, naturally, by a native');
lines.push('speaker. Quiet room; a phone mic is fine. Save the file at exactly the');
lines.push('path shown (under `learn-app/public/`), run `npm run build`, and the app');
lines.push('uses it automatically — no code changes. `-slow.mp3` rows are the same');
lines.push('phrase spoken slowly with clear word breaks (optional but valuable).');
lines.push('');

const dirs = [...byDir.keys()].sort();
for (const dir of dirs) {
  const items = byDir.get(dir).sort((a, b) => a.path.localeCompare(b.path));
  lines.push(`## \`${dir}/\``);
  lines.push('');
  lines.push('| ✔ | File | Say (Telugu) | Sounds like | Meaning |');
  lines.push('|---|------|--------------|-------------|---------|');
  for (const it of items) {
    const exists = existsSync(join(publicDir, it.path));
    if (exists) done++; else missing++;
    const file = it.path.slice(it.path.lastIndexOf('/') + 1);
    lines.push(`| ${exists ? '✅' : '⬜'} | \`${file}\` | ${it.telugu || '—'} | *${it.translit || ''}* | ${it.english || ''} |`);
  }
  lines.push('');
}

lines.unshift('');
lines.splice(1, 0, `**Status: ${done} recorded · ${missing} still needed (${files.size} total files).**`);
lines.unshift('# Audio recording checklist');
// remove the duplicate header added above
lines.splice(3, 1);

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, lines.join('\n') + '\n');
console.log(`✅ wrote ${outPath}`);
console.log(`   ${done} recorded, ${missing} needed, across ${dirs.length} folders`);
